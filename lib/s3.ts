import { S3Client } from "@aws-sdk/client-s3"

let client: S3Client | undefined

/** Bucket name when S3-compatible storage is configured (Garage, OVH…), else null. */
export const s3Bucket = () =>
  process.env.S3_ENDPOINT &&
  process.env.S3_BUCKET &&
  process.env.S3_ACCESS_KEY_ID &&
  process.env.S3_SECRET_ACCESS_KEY
    ? process.env.S3_BUCKET
    : null

export const getS3 = () =>
  (client ??= new S3Client({
    endpoint: process.env.S3_ENDPOINT,
    region: process.env.S3_REGION || "us-east-1",
    credentials: {
      accessKeyId: process.env.S3_ACCESS_KEY_ID ?? "",
      secretAccessKey: process.env.S3_SECRET_ACCESS_KEY ?? "",
    },
    // Self-hosted and OVH endpoints address buckets by path, not subdomain.
    forcePathStyle: true,
  }))

/** Public path of a stored image: served by app/media, so the bucket stays private. */
export const MEDIA_PREFIX = "/media/"

/** Keys generated by lib/storage: `<preset>-<timestamp>-<random>.webp`. */
export const MEDIA_KEY_PATTERN = /^[a-z]+-\d+-[a-z0-9]+\.webp$/
